"""Generate a skill's references/rule-index.md from its rules.json + reference headings."""

from __future__ import annotations

import json
import re
from pathlib import Path

HEADING = re.compile(r"^## (\d{2})\. (.+?)\s*$", re.M)
CHECK_LABEL = {
    "auto": "auto", "heuristic": "heuristic", "build": "build output", "live": "live URL / remote / host",
    "tool": "delegated tool", "manual": "manual",
}


def anchor(nn: str, title: str) -> str:
    slug = re.sub(r"[^\w\s-]", "", f"{nn}. {title}".lower())
    return re.sub(r"\s+", "-", slug.strip())


def load(skill: Path) -> tuple[dict, dict[str, dict[str, str]], list[str]]:
    meta = json.loads((skill / "rules.json").read_text(encoding="utf-8"))
    refs = skill / "references"
    titles: dict[str, dict[str, str]] = {}
    problems: list[str] = []
    for prefix, fname in meta["files"].items():
        found = dict(HEADING.findall((refs / fname).read_text(encoding="utf-8")))
        titles[prefix] = found
        declared = set(meta["rules"].get(prefix, {}))
        problems += [f"{fname} §{nn} '{found[nn]}' has no entry in rules.json[{prefix}]" for nn in sorted(set(found) - declared)]
        problems += [f"rules.json[{prefix}][{nn}] has no '## {nn}.' heading in {fname}" for nn in sorted(declared - set(found))]
        for nn, e in meta["rules"].get(prefix, {}).items():
            if e[0] not in CHECK_LABEL or e[1] not in ("error", "warn", "info"):
                problems.append(f"rules.json[{prefix}][{nn}] invalid check/severity: {e}")
    return meta, titles, problems


def render(meta: dict, titles: dict[str, dict[str, str]], generator: str) -> str:
    total = sum(len(v) for v in meta["rules"].values())
    counts: dict[str, int] = {}
    for dom in meta["rules"].values():
        for e in dom.values():
            counts[e[0]] = counts.get(e[0], 0) + 1
    out = [
        "# Rule Index", "",
        f"<!-- Generated by {generator} from rules.json. Do not edit by hand. -->", "",
        f"{total} rules. Rule `prefix.NN` = section `NN` of the file. **Check** says how a rule is verified:", "",
        "- **auto**: deterministic static check",
        "- **heuristic**: static check that can produce false positives; open the file and confirm before reporting",
        "- **build output**: needs build output",
        "- **live URL / remote / host**: needs a live target (`--url`, `--remote`, a running daemon, or the server)",
        "- **delegated tool**: hand off to another tool",
        "- **manual**: needs judgment; listed under \"not checked\" in reports", "",
        "Coverage: " + " · ".join(f"{CHECK_LABEL[k]} {v}" for k, v in sorted(counts.items(), key=lambda kv: -kv[1])), "",
    ]
    for prefix, fname in meta["files"].items():
        out += [f"## `{prefix}` · [{fname}]({fname})", "", "| Rule | Title | Check | Default severity | OWASP |", "|---|---|---|---|---|"]
        for nn in sorted(meta["rules"][prefix]):
            e = meta["rules"][prefix][nn]
            title = titles[prefix].get(nn, "?")
            owasp = ", ".join(e[2]) if len(e) > 2 else ""
            out.append(f"| `{prefix}.{nn}` | [{title}]({fname}#{anchor(nn, title)}) | {CHECK_LABEL[e[0]]} | {e[1]} | {owasp} |")
        out.append("")
    return "\n".join(out)


def build(skill: Path, check: bool, generator: str = "scripts/build_rule_index.py") -> tuple[int, str]:
    meta, titles, problems = load(skill)
    text = render(meta, titles, generator)
    target = skill / "references" / "rule-index.md"
    msgs = [f"problem: {p}" for p in problems]
    if check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            msgs.append("rule-index.md is out of date: run scripts/build_rule_index.py")
            return 1, "\n".join(msgs)
        return (1 if problems else 0), "\n".join(msgs)
    target.write_text(text, encoding="utf-8", newline="\n")
    msgs.append(f"wrote {target} ({sum(len(v) for v in meta['rules'].values())} rules)")
    return (1 if problems else 0), "\n".join(msgs)
